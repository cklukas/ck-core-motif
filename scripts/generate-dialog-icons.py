#!/usr/bin/env python3
"""Embed the maintained SVG artwork without a runtime asset-path dependency."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
output = root / "lib/Xm/DialogIconsI.h"
lines = ["/* Generated by scripts/generate-dialog-icons.py; edit icons/dialog-*.svg. */",
         "static const struct { const char *name; const char *source; } dialog_svg_icons[] = {"]
for path in sorted((root / "lib/Xm/icons").glob("dialog-*.svg")):
    name = path.stem.replace("-", "_")
    lines.append("    {" + json.dumps(name) + ",")
    lines.extend("     " + json.dumps(line) for line in path.read_text().splitlines(keepends=True))
    lines.append("    },")
lines.append("};")
content = "\n".join(lines) + "\n"
if args.check:
    if output.read_text() != content:
        raise SystemExit("DialogIconsI.h is stale; run scripts/generate-dialog-icons.py")
else:
    output.write_text(content)
