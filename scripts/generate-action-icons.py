#!/usr/bin/env python3
"""Generate embedded action SVGs and monochrome fallbacks from shared geometry."""
import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SIZE = 24
INK = "#46566b"
PAPER = "#f4eee0"
BLUE = "#7296bd"
GOLD = "#d9b16d"
GREEN = "#78a487"


def rect(x, y, width, height, fill):
    return ([(x, y), (x + width, y), (x + width, y + height), (x, y + height)], fill, True)


def line(*points):
    return (points, "none", False)


ICONS = {
    "open": [( [(2, 6), (9, 6), (12, 9), (21, 9), (21, 20), (2, 20)], GOLD, True),
             ([(4, 12), (23, 12), (19, 20), (1, 20)], "#efce90", True)],
    "document": [([(5, 2), (14, 2), (20, 8), (20, 22), (5, 22)], PAPER, True),
                 ([(14, 2), (14, 8), (20, 8)], BLUE, True),
                 line((8, 12), (17, 12)), line((8, 15), (17, 15)), line((8, 18), (14, 18))],
    "save": [([(3, 2), (19, 2), (22, 5), (22, 22), (3, 22)], BLUE, True),
             rect(7, 2, 10, 7, PAPER), rect(14, 3, 2, 5, INK), rect(7, 13, 11, 9, PAPER),
             line((10, 16), (15, 16)), line((10, 19), (15, 19))],
    "print": [rect(6, 2, 13, 8, PAPER), rect(2, 9, 21, 10, "#a9b4bf"),
              rect(6, 15, 13, 7, PAPER), line((9, 18), (16, 18)), line((19, 12), (21, 12))],
    "undo": [([(10, 3), (2, 10), (10, 17), (10, 12), (16, 12), (19, 15),
               (19, 21), (23, 21), (23, 14), (18, 8), (10, 8)], GREEN, True)],
    "picture": [rect(2, 3, 21, 18, PAPER), rect(5, 6, 15, 12, "#a9c8dc"),
                ([(5, 18), (10, 10), (14, 15), (17, 12), (20, 18)], GREEN, True),
                rect(16, 8, 2, 2, GOLD)],
    "archive": [rect(4, 7, 17, 15, GOLD), rect(2, 3, 21, 5, "#efd39a"),
                rect(9, 11, 7, 4, PAPER)],
}


def segment(bitmap, start, end):
    x, y = start
    x1, y1 = end
    dx, dy = abs(x1 - x), -abs(y1 - y)
    sx, sy = 1 if x < x1 else -1, 1 if y < y1 else -1
    error = dx + dy
    while True:
        if 0 <= x < SIZE and 0 <= y < SIZE:
            bitmap[y * 3 + x // 8] |= 1 << (x % 8)
        if (x, y) == (x1, y1):
            break
        twice = 2 * error
        if twice >= dy:
            error += dy
            x += sx
        if twice <= dx:
            error += dx
            y += sy


def generate():
    rows = ["/* Generated by scripts/generate-action-icons.py. */",
            "static const struct { const char *name; const char *svg; unsigned char bits[72]; } action_icons[] = {"]
    outputs = {}
    for name, shapes in ICONS.items():
        svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">',
               f"<title>{html.escape(name.title())}</title>"]
        bitmap = bytearray(72)
        for points, fill, closed in shapes:
            tag = "polygon" if closed else "polyline"
            coords = " ".join(f"{x},{y}" for x, y in points)
            svg.append(f'<{tag} points="{coords}" fill="{fill}" stroke="{INK}" stroke-width="1" stroke-linejoin="round" stroke-linecap="round"/>')
            edges = list(zip(points, points[1:]))
            if closed:
                edges.append((points[-1], points[0]))
            for first, last in edges:
                segment(bitmap, first, last)
        svg.append("</svg>")
        source = "\n".join(svg) + "\n"
        outputs[ROOT / "lib/Xm/icons" / f"action-{name}.svg"] = source
        rows.append("    {" + json.dumps("action_" + name) + ",")
        rows.extend("     " + json.dumps(line) for line in source.splitlines(keepends=True))
        rows.append("     , {" + ",".join(f"0x{byte:02x}" for byte in bitmap) + "}},")
    rows.append("};")
    outputs[ROOT / "lib/Xm/ActionIconsI.h"] = "\n".join(rows) + "\n"
    return outputs


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated artwork: {path}")
        else:
            path.write_text(content)
