#!/usr/bin/env python3
"""Check dynamic Container tab-list creation validates its widget input."""
from pathlib import Path


source = (Path(__file__).resolve().parents[2] / "lib" / "Xm" / "Container.c").read_text(
    encoding="utf-8"
)
start = source.rindex("SetDynamicTabList(\n")
region = source[start : source.index("\n}\n", start)]
assert region.index("if (wid == NULL)") < region.index("cw = (XmContainerWidget)wid")
assert "return(NULL);" in region

print("PASS dynamic Container tab-list creation validates widget input")
